"""Write .github/codecov.yml: one Codecov component per area of specs/areas.toml.

Each component's paths are anchored prefix regexes. ``spec_tools.area_for``
gives a file to its longest matching prefix (an unowned prefix wins a tie), so
a prefix that contains a longer prefix of another owner gets a negative
lookahead for it: ``templates/pep_`` excludes the unowned ``pep_cri_``, and
``baseline/`` (parity) excludes ``baseline/simple_open_``.
tests/scripts/test_codecov_components.py checks both the file and the
classification of every source file.

    uv run python scripts/dev/codecov_components.py
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
from spec_tools import Areas, load_areas  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
CONFIG = ROOT / ".github" / "codecov.yml"

HEADER = """\
# Generated by scripts/dev/codecov_components.py from specs/areas.toml: do not
# edit component_management by hand. Coverage is informational for now (no
# floor yet, R-COVERAGE); it is measured on main (coverage.yml) over what CI runs,
# so GAMS and slow tests are not counted.
"""

SETTINGS = {
    "coverage": {
        "status": {
            "project": {"default": {"informational": True}},
            "patch": {"default": {"informational": True}},
        }
    },
    "comment": {
        "layout": "condensed_header, diff, flags, components",
        "require_changes": False,
    },
}


def _regex(prefix: str, owner: str | None, owners: list[tuple[str | None, str]]) -> str:
    longer = sorted(
        q[len(prefix) :]
        for o, q in owners
        if o != owner and q != prefix and q.startswith(prefix)
    )
    look = f"(?!{'|'.join(re.escape(s) for s in longer)})" if longer else ""
    return f"^{re.escape(prefix)}{look}"


def component_management(areas: Areas) -> dict:
    owners: list[tuple[str | None, str]] = [
        (name, p) for name, prefixes in areas.areas.items() for p in prefixes
    ] + [(None, p) for p in areas.unowned]
    components = [
        {
            "component_id": re.sub(r"\W", "_", name),
            "name": name,
            "paths": [_regex(p, name, owners) for p in prefixes],
        }
        for name, prefixes in areas.areas.items()
    ]
    return {"individual_components": components}


def render(areas: Areas) -> str:
    body = {**SETTINGS, "component_management": component_management(areas)}
    return HEADER + yaml.safe_dump(body, sort_keys=False, width=100)


def main() -> int:
    CONFIG.write_text(
        render(load_areas(ROOT / "specs" / "areas.toml")), encoding="utf-8"
    )
    print(f"wrote {CONFIG.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
