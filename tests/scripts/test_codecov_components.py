"""Codecov's per-area coverage comes from specs/areas.toml, not a hand-kept copy.

``.github/codecov.yml`` lists one Codecov component per area. Its path regexes
are generated by ``scripts/dev/codecov_components.py`` and must classify every
source file exactly as ``spec_tools.area_for`` does (longest prefix wins; an
unowned prefix beats a coarser owner).
"""

from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "scripts" / "dev"))
import codecov_components  # noqa: E402  # ty: ignore[unresolved-import]
import spec_tools  # noqa: E402  # ty: ignore[unresolved-import]

AREAS = spec_tools.load_areas(ROOT / "specs" / "areas.toml")
CONFIG = ROOT / ".github" / "codecov.yml"


def _src_files() -> list[str]:
    out = subprocess.run(["git", "-C", str(ROOT), "ls-files", "src/equilibria"],
                         capture_output=True, text=True, check=True).stdout  # fmt: skip
    return [p for p in out.splitlines() if p.endswith(".py")]


def _classify(path: str, components: list[dict]) -> str | None:
    hits = [c["name"] for c in components if any(re.match(r, path) for r in c["paths"])]
    assert len(hits) <= 1, (path, hits)
    return hits[0] if hits else None


def test_config_is_generated_from_areas() -> None:
    config = yaml.safe_load(CONFIG.read_text(encoding="utf-8"))
    assert config["component_management"] == codecov_components.component_management(
        AREAS
    )


def test_components_classify_like_area_for() -> None:
    components = codecov_components.component_management(AREAS)["individual_components"]
    files = _src_files()
    assert len(files) > 100
    wrong = [
        (p, _classify(p, components), spec_tools.area_for(p, AREAS))
        for p in files
        if _classify(p, components) != spec_tools.area_for(p, AREAS)
    ]
    assert wrong == []


def test_the_overlaps_are_resolved() -> None:
    """The two prefixes that contain another area's prefix (the reason for the
    lookaheads): a pep_cri_ file is unowned, a baseline/simple_open_ file is
    simple_open's, not parity's."""
    components = codecov_components.component_management(AREAS)["individual_components"]
    assert _classify("src/equilibria/templates/pep_cri_x.py", components) is None
    assert (
        _classify("src/equilibria/templates/pep_pyomo.py", components)
        == "templates/pep"
    )
    assert _classify("src/equilibria/baseline/simple_open_x.py", components) == (
        "templates/simple_open"
    )
    assert _classify("src/equilibria/baseline/other.py", components) == "parity"


def _workflow(name: str) -> dict:
    return yaml.safe_load((ROOT / ".github" / "workflows" / name).read_text())


def test_pull_requests_do_not_measure_coverage() -> None:
    """Measured on python 3.11 with branches, coverage made python-tests 3x
    slower in CI (24 -> 75 min) and gdxdump-tests 2x (30 -> 61 min)."""
    runs = " ".join(
        s.get("run", "") + str(s.get("uses", ""))
        for job in _workflow("tests.yml")["jobs"].values()
        for s in job["steps"]
    )
    assert "--cov" not in runs and "codecov" not in runs


def test_coverage_runs_on_main_with_sysmon() -> None:
    """Python 3.13's sys.monitoring tracer, lines only: +8 % on a GTAP test
    (12.3 -> 13.3 s), against +62 % for branches on the old tracer."""
    wf = _workflow("coverage.yml")
    on = wf[True] if True in wf else wf["on"]  # YAML 1.1 reads `on` as true
    assert set(on) == {"push", "workflow_dispatch"} and on["push"]["branches"] == [
        "main"
    ]
    (job,) = wf["jobs"].values()
    assert job["env"]["COVERAGE_CORE"] == "sysmon"
    parts = {p["name"]: p["marks"] for p in job["strategy"]["matrix"]["part"]}
    assert parts == {
        "python-tests": "not gams and not slow and not needs_gdxdump",
        "gdxdump-tests": "needs_gdxdump and not gams and not slow",
    }
    steps = job["steps"]
    setup = next(
        s for s in steps if s.get("uses") == "./.github/actions/setup-test-env"
    )
    assert setup["with"]["python-version"] == "3.13"
    runs = " ".join(s.get("run", "") for s in steps)
    assert "--cov --cov-report=xml" in runs and "${{ matrix.part.marks }}" in runs
    (upload,) = [s for s in steps if str(s.get("uses", "")).startswith("codecov/")]
    assert upload["with"]["token"] == "${{ secrets.CODECOV_TOKEN }}"
    assert upload["with"]["flags"] == "${{ matrix.part.name }}"


def test_coverage_counts_lines_not_branches() -> None:
    """sys.monitoring traces branches only from Python 3.14 on."""
    import tomllib  # ty: ignore[unresolved-import]  (3.11+; CI runs 3.11)

    run = tomllib.loads((ROOT / "pyproject.toml").read_text())["tool"]["coverage"][
        "run"
    ]
    assert run["branch"] is False
